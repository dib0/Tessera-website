// Regenerates site/logo.tes from the official logo in the Tessera language repository.
//   node tools/embed_logo.mjs ../Tessera-language/resources/tessera-logo.svg site/logo.tes
// Text literals in Tessera cannot span lines and need backslash and double quote escaped,
// so the SVG is embedded line by line.
import { readFileSync, writeFileSync } from "node:fs";

const [source, target] = process.argv.slice(2);
if (!source || !target) {
  console.error("usage: node tools/embed_logo.mjs <logo.svg> <output.tes>");
  process.exit(2);
}
const BACKSLASH = String.fromCharCode(92);
const QUOTE = String.fromCharCode(34);
const escape = (line) => line.split(BACKSLASH).join(BACKSLASH + BACKSLASH).split(QUOTE).join(BACKSLASH + QUOTE);
const literal = (line) => QUOTE + escape(line) + QUOTE;
const NEWLINE_ESCAPE = BACKSLASH + "n";

const lines = readFileSync(source, "utf8").split(/\r?\n/).map((l) => l.trim()).filter((l) => l.length > 0);
const full = lines.map(literal).join(",\n");

const tile = (x, y, fill) => `<rect x='${x}' y='${y}' width='34' height='34' rx='7' fill='url(#${fill})'/>`;
const gradient = (id, from, to) =>
  `<linearGradient id='${id}' x1='0' y1='0' x2='1' y2='1'><stop stop-color='${from}'/><stop offset='1' stop-color='${to}'/></linearGradient>`;
const mark = [
  "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 108 108' width='108' height='108' role='img' aria-label='Tessera'>",
  "<defs>" +
    [
      gradient("a", "#4C7DFF", "#1745B8"),
      gradient("b", "#50E5D0", "#008C91"),
      gradient("c", "#FFE39A", "#D98B32"),
      gradient("d", "#71C9FF", "#3263D9"),
      gradient("e", "#8A75FF", "#197D9A"),
    ].join("") +
    "</defs>",
  tile(0, 0, "a") + tile(37, 0, "b") + tile(74, 0, "c") + tile(37, 37, "d") + tile(37, 74, "e"),
  "</svg>",
]
  .map(literal)
  .join(",\n");

const output = `// Generated by tools/embed_logo.mjs. Do not edit.

note "The official Tessera logo (from the language repository), as SVG text."
pub fn full() -> Text = join([
${full}
], ${QUOTE}${NEWLINE_ESCAPE}${QUOTE})

note "The five-tile T mark, used in the page header and as the icon."
pub fn mark() -> Text = join([
${mark}
], ${QUOTE}${NEWLINE_ESCAPE}${QUOTE})
`;
writeFileSync(target, output, { encoding: "utf8" });
